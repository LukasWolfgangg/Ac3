def shape(w,x,N1=0.5,N2=1.0):
    w=np.array(w); N=len(w)-1
    S=sum(w[i]*comb(N,i)*x**i*(1-x)**(N-i) for i in range(N+1))
    return x**N1*(1-x)**N2*S
